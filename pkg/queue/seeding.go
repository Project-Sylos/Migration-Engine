// SeedRootTask inserts the initial root folder task into DuckDB to kickstart traversal.
// traversalStatus is typically pending (classic round 0) or successful (UI-prepared round 0 done).
// For src: sets copy_status='already_existed' (root is not a copy task).
// rootNodeID should be db.MintNodeID(queueType, "", db.NodeTypeFolder, "/").
func SeedRootTask(queueType string, rootFolder types.Folder, rootNodeID string, database *db.DB, traversalStatus string) error {
	if database == nil {
		return fmt.Errorf("database cannot be nil")
	}

	if rootNodeID == "" {
		return fmt.Errorf("rootNodeID cannot be empty - must be generated by db.MintNodeID()")
	}
	if traversalStatus == "" {
		traversalStatus = db.StatusPending
	}

	_, _, ok := pull.GetRootNode(database, queueType)
	if ok {
		return nil
	}

	state := &db.NodeState{
		ID:              rootNodeID,
		ServiceID:       rootFolder.ServiceID,
		ParentID:        "",
		ParentServiceID: rootFolder.ParentId,
		ParentPath:      "",
		Name:            rootFolder.DisplayName,
		DisplayPath:     filter.RootDisplayPath(),
		Path:            "/",
		Type:            types.NodeTypeFolder,
		Size:            0,
		MTime:           rootFolder.LastUpdated,
		Depth:           0,
		Status:          traversalStatus,
	}

	state.TraversalStatus = traversalStatus
	if queueType == "SRC" {
		state.CopyStatus = db.CopyStatusAlreadyExisted
	}

	if err := pull.InsertRootNode(database, queueType, state); err != nil {
		return fmt.Errorf("failed to seed root task for %s: %w", queueType, err)
	}

	if logservice.LS != nil {
		err := logservice.LS.Log(
			"info",
			fmt.Sprintf("Seeded root task: %s (path: %s, traversal=%s)", rootFolder.DisplayName, rootFolder.LocationPath, traversalStatus),
			"seeding",
			queueType,
		)
		if err != nil {
			fmt.Println("error logging", err)
		}
	}

	return nil
}

// SeedRootTasksPrepared seeds roots; prepared sides get traversal-successful roots.
func SeedRootTasksPrepared(srcRoot, dstRoot types.Folder, database *db.DB, srcPrepared, dstPrepared bool) error {
	_, _, srcOk := pull.GetRootNode(database, "SRC")
	_, _, dstOk := pull.GetRootNode(database, "DST")
	if srcOk && dstOk {
		return nil
	}

	srcRootID := db.MintNodeID("SRC", "", db.NodeTypeFolder, "/")
	dstRootID := db.MintNodeID("DST", "", db.NodeTypeFolder, "/")

	srcTrav := db.StatusPending
	if srcPrepared {
		srcTrav = db.StatusSuccessful
	}
	dstTrav := db.StatusPending
	if dstPrepared {
		dstTrav = db.StatusSuccessful
	}

	if err := SeedRootTask("SRC", srcRoot, srcRootID, database, srcTrav); err != nil {
		return fmt.Errorf("failed to seed src root: %w", err)
	}

	if err := SeedRootTaskWithSrcID("DST", dstRoot, dstRootID, srcRootID, database, dstTrav); err != nil {
		return fmt.Errorf("failed to seed dst root: %w", err)
	}

	database.AppendIDMapEvent(db.IDMapEvent{
		SrcInternalID: srcRootID,
		DstInternalID: dstRootID,
		Source:        db.IDMapSourceRootSeed,
		Status:        db.IDMapStatusActive,
		Depth:         0,
	})

	if err := database.Checkpoint(); err != nil {
		fmt.Println("error checkpointing", err)
	}

	if logservice.LS != nil {
		err := logservice.LS.Log(
			"info",
			"Successfully seeded both src and dst root tasks",
			"seeding",
			"main",
		)
		if err != nil {
			fmt.Println("error logging", err)
		}
	}

	return nil
}

// SeedRootTaskWithSrcID inserts the DST root with SrcID linking to the SRC root.
